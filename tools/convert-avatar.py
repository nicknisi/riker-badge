#!/usr/bin/env python3
"""Freeze supplied GIFs into deduplicated RGB565 frames (requires Pillow)."""
from pathlib import Path
from PIL import Image, ImageSequence

root = Path(__file__).resolve().parents[1]
output = """// Generated by tools/convert-avatar.py. Original GIF timing is preserved.
#pragma once
#include <stdint.h>
struct NickAnimation {
    uint16_t width, height, count;
    uint32_t duration;
    const uint16_t* delays;
    const uint8_t* indices;
    const uint16_t* pixels;
};
"""
for name, filename in [("PEEK", "nick.gif"), ("BLINK", "nick-blink.gif"), ("WAIT", "nick-wait.gif")]:
    image = Image.open(root / "assets" / filename)
    width, height = image.size
    unique, lookup, indices, durations = [], {}, [], []
    for frame in ImageSequence.Iterator(image):
        background = Image.new("RGBA", image.size, "black")
        background.alpha_composite(frame.convert("RGBA"))
        raw = background.convert("RGB").tobytes()
        pixels = tuple(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                       for r, g, b in zip(raw[0::3], raw[1::3], raw[2::3]))
        if pixels not in lookup:
            lookup[pixels] = len(unique)
            unique.append(pixels)
        indices.append(lookup[pixels])
        durations.append(max(20, frame.info.get("duration", 100)))
        assert unique[indices[-1]] == pixels
    assert 0 < len(unique) <= 256 and len(indices) == image.n_frames
    assert all(0 < duration <= 65535 for duration in durations)
    assert all(len(frame) == width * height for frame in unique)
    output += f"static const uint16_t {name}_DELAYS[] = {{" + ",".join(map(str, durations)) + "};\n"
    output += f"static const uint8_t {name}_INDICES[] = {{" + ",".join(map(str, indices)) + "};\n"
    output += f"static const uint16_t {name}_PIXELS[][{width * height}] = {{\n"
    for frame in unique:
        output += "{" + ",".join(f"0x{p:04x}" for p in frame) + "},\n"
    output += "};\n"
    output += f"static const NickAnimation NICK_{name} = {{{width}, {height}, {len(indices)}, {sum(durations)}, {name}_DELAYS, {name}_INDICES, &{name}_PIXELS[0][0]}};\n"
    print(f"{name}: {len(indices)} frames, {len(unique)} unique, {sum(durations)} ms, {len(unique)*width*height*2:,} pixel bytes")
(root / "components/badge_display/nick_frames.h").write_text(output)
