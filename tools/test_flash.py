"""Host-only safety checks: no serial access or flash writes."""
import struct
import zlib
from flash import active_slot, check_image, check_layout


def rejected(fn, arg):
    try:
        fn(arg)
    except ValueError:
        return
    raise AssertionError("unsafe input was accepted")


def entry(seq, state=2):
    raw = bytearray(32)
    struct.pack_into("<I", raw, 0, seq)
    struct.pack_into("<II", raw, 24, state, zlib.crc32(raw[:4], 0xffffffff))
    return raw


if __name__ == "__main__":
    ota = bytearray(b"\xff" * 8192)
    rejected(active_slot, ota)
    # Captured from the device-verified original OTA metadata, not generated by this helper.
    assert zlib.crc32(b"\x01\x00\x00\x00", 0xffffffff) == 0x4743989a
    ota[:32] = entry(1)
    assert active_slot(ota) == 0
    ota[4096:4128] = entry(2)
    assert active_slot(ota) == 1
    ota[4096:4128] = entry(2, 3)  # aborted image cannot win
    assert active_slot(ota) == 0
    ota[0] ^= 4
    rejected(active_slot, ota)
    image = bytearray(32)
    image[0] = 0xe9
    struct.pack_into("<H", image, 12, 9)
    check_image(image)
    check_image(image + bytes(0x300000 - len(image)))
    rejected(check_image, image + bytes(0x300000 - len(image) + 1))
    image[12] = 0
    rejected(check_image, image)
    table = b"".join(struct.pack("<HBBII16sI", 0x50aa, kind, subkind, start, size, name, 0)
        for name, kind, subkind, start, size in [
            (b"app0", 0, 0x10, 0x10000, 0x300000),
            (b"app1", 0, 0x11, 0x310000, 0x300000),
            (b"ffat", 1, 0x81, 0x610000, 0x9e0000)])
    check_layout(table)
    rejected(check_layout, table[:64])
    wrong = bytearray(table)
    struct.pack_into("<I", wrong, 4, 0x20000)
    rejected(check_layout, wrong)
    print("Flash guards passed: OTA CRC/state, chip, size, and preserved layout")
